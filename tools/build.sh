#!/usr/bin/env bash
# Goodness Engine — build the single-file bundle into dist/goodness.js
# Usage: bash tools/build.sh
set -euo pipefail
cd "$(dirname "$0")/.."

mkdir -p dist
OUT=dist/goodness.js

echo "/* Goodness Engine bundle — generated by tools/build.sh
   Source: https://github.com/goodness1202/goodness
   Include this one file, then:
     GE.api.boot_project(project, canvasElement);
*/" > "$OUT"

# parse the manifest from engine/loader.js (single source of truth)
FILES=$(node -e "
const fs = require('fs');
const src = fs.readFileSync('engine/loader.js', 'utf8');
const files = [...src.match(/FILES\s*=\s*\[([^\]]+)\]/)[1].matchAll(/'([^']+)'/g)].map(x => x[1]);
console.log(files.join('\n'));
")

while IFS= read -r f; do
  echo "" >> "$OUT"
  cat "$f" >> "$OUT"
done <<< "$FILES"

echo "✓ built $OUT ($(wc -l < "$OUT") lines, $(du -h "$OUT" | cut -f1))"
